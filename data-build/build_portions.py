#!/usr/bin/env python3
"""Generate app/data/portions.js from data-build/reference/portions.json.

The reference JSON carries, per food id, the FDA reference amount (21 CFR 101.12 RACC), a typical and a maximum
portion per eating occasion (USDA ARS NFS Report 96-5 intake percentiles, or a labelled derivation), a daily
maximum where one is meaningful, and the minimum portion when the food is a dish's named protein, each with its
source string. The app only needs the numbers, so this writes a compact map. Never hand-edit portions.js.
"""
import io, json, os
HERE = os.path.dirname(os.path.abspath(__file__))
src = json.load(io.open(os.path.join(HERE, "reference", "portions.json"), encoding="utf-8"))
out = {}
for r in src:
    e = {}
    for k_src, k_out in (("typical_meal_g","typ"),("max_meal_g","max"),("max_day_g","day"),("min_as_star_g","star"),("racc_g","racc")):
        v = r.get(k_src)
        if isinstance(v, (int, float)) and v > 0: e[k_out] = round(float(v), 1)
    if e: out[r["id"]] = e
js = ("// GENERATED by data-build/build_portions.py from data-build/reference/portions.json. Do not edit by hand.\n"
      "// Per food id: typ = typical portion per meal, max = most a large but normal eater plates in one sitting,\n"
      "// day = daily maximum where meaningful, star = minimum when it is the dish's named protein, racc = FDA\n"
      "// reference amount (21 CFR 101.12). Grams, in the food's own basis (cooked/dry/raw as named). Sources are\n"
      "// in the reference JSON.\n"
      "window.OB_PORTIONS = " + json.dumps(out, separators=(",",":")) + ";\n")
io.open(os.path.join(HERE, "..", "app", "data", "portions.js"), "w", encoding="utf-8").write(js)
print("wrote app/data/portions.js:", len(out), "foods")
