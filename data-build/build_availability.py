#!/usr/bin/env python3
"""Generate app/data/availability.js from data-build/reference/availability.json.

The reference file classifies every food by how easy it is to buy in the US (2026-09-24 audit: live shelf checks
at a Walmart and an Aldi plus retailer pages, evidence and sources per food):
  everywhere  essentially every US supermarket and big-box store
  most        most full-size supermarkets, but not every store (a small-town store or Aldi may not have it)
  specialty   natural-food stores, specialty markets or online only
  homemade    a recipe made from its ingredients
The planner drafts from everywhere/most foods and only uses a specialty food when the coach says the client can buy
it. OVERRIDES below are decisions made after the audit, each with its reason. Never hand-edit availability.js.
"""
import io, json, os
HERE = os.path.dirname(os.path.abspath(__file__))
OVERRIDES = {
    # plain psyllium is classed specialty, but the same husk is on the Walmart shelf as Metamucil Sugar-Free and
    # store-brand psyllium fibre powder; the fibre fallback needs it. Kept drafted, flagged "most".
    "Psyllium husk": "most",
}
src = json.load(io.open(os.path.join(HERE, "reference", "availability.json"), encoding="utf-8"))
out = {}
for r in src:
    t = OVERRIDES.get(r["name"], r["tier"])
    e = {"t": t}
    sw = (r.get("everywhere_substitute_short") or "").strip()
    if sw and t in ("most", "specialty"): e["s"] = sw
    out[r["id"]] = e
js = ("// GENERATED by data-build/build_availability.py from data-build/reference/availability.json. Do not edit by hand.\n"
      "// t = everywhere | most | specialty | homemade (how easy the food is to buy in the US); s = everyday swap.\n"
      "window.OB_AVAIL = " + json.dumps(out, separators=(",",":"), ensure_ascii=False) + ";\n")
io.open(os.path.join(HERE, "..", "app", "data", "availability.js"), "w", encoding="utf-8").write(js)
from collections import Counter
print("wrote app/data/availability.js:", len(out), "foods", dict(Counter(v["t"] for v in out.values())))
