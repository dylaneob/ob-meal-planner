// Builds app/data/retired_prep.js: fingerprints of OLD library batch recipes (prepMethod) and everyday recipes (method), so a
// saved client drafted before a recipe rewrite gets the current directions when the coach opens it. Only text that is byte-for-byte an old
// library version is upgraded; a hand-written recipe (a client's, a client's) never matches and is left alone.
// Usage: node tools/retired_prep.js <old templates.js> [<older templates.js> ...]
// 2026-10-06: built from the 2026-10-02 and 2026-10-05 libraries, when all 164 batch recipes were rewritten step by step.
// 2026-10-06 (later): everyday recipes too (OB_RETIRED_METHOD), adding the library from before their step-by-step rewrite.
// The snapshots it is built from are kept in data-build/library-snapshots/; to rebuild:
//   node tools/retired_prep.js data-build/library-snapshots/*.js
"use strict";
const fs = require("fs"), path = require("path");
const OUT = path.join(__dirname, "..", "app", "data", "retired_prep.js");
const djb2 = s => { let h = 5381; for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) | 0; return h; };
const load = file => { global.window = global; delete window.OB_MEAL_TEMPLATES; delete require.cache[require.resolve(path.resolve(file))]; require(path.resolve(file)); return window.OB_MEAL_TEMPLATES; };
const current = load(path.join(__dirname, "..", "app", "data", "templates.js"));
const now = new Map(current.filter(t => t.prepMethod).map(t => [t.title, t.prepMethod]));
const nowM = new Map(current.filter(t => !t.prepMethod && t.method).map(t => [t.title, t.method]));
const files = process.argv.slice(2);
if (!files.length) { console.log("usage: node tools/retired_prep.js <old templates.js> ..."); process.exit(2); }
const old = {}, oldM = {};
let kept = 0;
for (const f of files) for (const t of load(f)) {
  if (t.method && nowM.has(t.title) && nowM.get(t.title) !== t.method) oldM[djb2(t.method)] = t.title;
  if (!t.prepMethod || !now.has(t.title) || now.get(t.title) === t.prepMethod) continue;
  old[djb2(t.prepMethod)] = t.title; kept++;
}
const body = "// GENERATED by tools/retired_prep.js: do not edit by hand. Old library recipe text (djb2 of prepMethod, and of an everyday\n"
  + "// recipe's method) -> dish title. A saved client whose meal still carries one of these gets the current recipe when it is opened.\n"
  + "window.OB_RETIRED_PREP = " + JSON.stringify(old) + ";\n"
  + "window.OB_RETIRED_METHOD = " + JSON.stringify(oldM) + ";\n";
fs.writeFileSync(OUT, body);
console.log(`wrote ${OUT}: ${Object.keys(old).length} retired batch texts (${kept} seen across ${files.length} snapshot${files.length > 1 ? "s" : ""}), ${Object.keys(oldM).length} retired everyday texts`);
